export function t(lang, key, params = {}) {
  const selectedLang = lang === 'हिंदी' ? 'हिंदी' : 'ENG';
  let text = translations[selectedLang]?.[key] || translations.ENG[key] || key;
  Object.keys(params).forEach((k) => {
    text = text.replace(`{${k}}`, params[k]);
  });
  return text;
}
